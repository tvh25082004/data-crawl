# ---------------------------------------------------------------- caches (Google-translated)
import json as _json
import os as _os

def _load_cache(*names):
    merged = {}
    base = _os.path.dirname(_os.path.abspath(__file__))
    for n in names:
        p = _os.path.join(base, n)
        if _os.path.exists(p):
            with open(p, encoding="utf-8") as f:
                merged.update(_json.load(f))
    return merged

_HDR_CACHE = {"vi": None, "en": None}
_VAL_CACHE = {"vi": None, "en": None}

def _hdr_cache(lang):
    if _HDR_CACHE[lang] is None:
        _HDR_CACHE[lang] = _load_cache(
            f"cache_headers_{lang}.json")
    return _HDR_CACHE[lang]

def _val_cache(lang):
    if _VAL_CACHE[lang] is None:
        _VAL_CACHE[lang] = _load_cache(
            f"cache_values_{lang}.json", f"cache_values2_{lang}.json")
    return _VAL_CACHE[lang]


# ------------------------------------------------------------------ utils
_TOK_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9\.\-%°/]*|[一-鿿]+|\S")
_TERM_VI_SORTED = sorted(TERM_VI.items(), key=lambda kv: len(kv[0]), reverse=True)
_TERM_EN_SORTED = sorted(TERM_EN.items(), key=lambda kv: len(kv[0]), reverse=True)


def _replace_terms(text: str, pairs) -> str:
    if not text or not any("一" <= ch <= "鿿" for ch in text):
        return text
    for src, dst in pairs:
        if src in text:
            # chèn space nếu kề chữ/số: "2WD豪华型" -> "2WD Cao cấp"
            text = re.sub(
                rf"([A-Za-z0-9%°]){re.escape(src)}",
                rf"\1 {dst}", text)
            text = re.sub(
                rf"{re.escape(src)}([A-Za-z0-9%°])",
                rf"{dst} \1", text)
            text = text.replace(src, dst)
    return text


def clean_value(v, lang="vi"):
    """Làm sạch + dịch 1 giá trị spec."""
    if v is None:
        return ""
    if isinstance(v, (int, float)):
        return v
    s = str(v).strip()
    if not s:
        return ""
    sym = SYM_MAP if lang == "vi" else SYM_MAP_EN
    if s in sym:
        return sym[s]
    if not any("一" <= ch <= "鿿" for ch in s):
        # không có chữ Hán -> giữ nguyên (tránh Google đổi 2.2L -> 2,2L)
        return s
    term_dict = TERM_VI if lang == "vi" else TERM_EN
    # match chính xác 1 thuật ngữ -> ưu tiên từ điển (chính xác hơn Google)
    if s in term_dict:
        return term_dict[s]
    # "5挡手动" -> "5 cấp số sàn"
    s2 = re.sub(r"(\d+)\s*挡\s*", (lambda m: m.group(1) + (" cấp " if lang == "vi" else "MT ")), s)
    if s2 != s:
        s = s2.strip()
    # "两年或10万公里" / "三年或10万公里" -> "3 năm hoặc 100.000 km"
    numzh = {"两": "2", "一": "1", "三": "3", "四": "4", "五": "5", "六": "6",
             "七": "7", "八": "8", "九": "9", "十": "10"}
    s_for_pat = s
    for zh, ar in numzh.items():
        s_for_pat = s_for_pat.replace(zh, ar)
    def _km(m):
        total = int(m.group(2)) * 10000
        txt = f"{total:,}".replace(",", ".") + " km"
        return f"{m.group(1)} {'năm' if lang == 'vi' else 'yr'} hoặc {txt}" if lang == "vi" else f"{m.group(1)} yr or {txt}"
    s3 = re.sub(r"(\d+)\s*年\s*或\s*(\d+)\s*万?\s*公里", _km, s_for_pat)
    if s3 != s_for_pat:
        s = s3
    else:
        s4 = re.sub(r"(\d+)\s*万\s*公里", (lambda m: f"{int(m.group(1))*10000:,}".replace(",", ".") + " km"), s_for_pat)
        if s4 != s_for_pat:
            s = s4
    # pattern: "X●" -> "X: Có"
    if "●" in s or "○" in s or "前-" in s or "后-" in s:
        parts = re.split(r"([、/])", s)
        out = []
        for p in parts:
            if p in ("、", "/"):
                out.append(" / " if p == "/" else ", ")
                continue
            p = p.strip()
            mark = ""
            if p.endswith("●"):
                p, mark = p[:-1].strip(), ("Có" if lang == "vi" else "Yes")
            elif p.endswith("○"):
                p, mark = p[:-1].strip(), ("Tuỳ chọn" if lang == "vi" else "Optional")
            elif p.endswith("-") and len(p) > 1:
                p, mark = p[:-1].strip(), ("Không" if lang == "vi" else "No")
            if p and mark:
                cached_p = _val_cache(lang).get(p)
                if cached_p and "●" not in cached_p:
                    p = cached_p
                else:
                    p = _replace_terms(p, _TERM_VI_SORTED if lang == "vi" else _TERM_EN_SORTED)
                out.append(f"{p}: {mark}")
            elif p:
                out.append(p)
        s = "".join(out).strip()
        s = re.sub(r"\s+", " ", s)
    # cache Google translate (exact match; bỏ nếu bản dịch còn dấu ●)
    if "●" not in s and "○" not in s:
        cached = _val_cache(lang).get(s)
        if cached and "●" not in cached and "○" not in cached:
            s = cached
        else:
            s = _replace_terms(s, _TERM_VI_SORTED if lang == "vi" else _TERM_EN_SORTED)
    else:
        s = _replace_terms(s, _TERM_VI_SORTED if lang == "vi" else _TERM_EN_SORTED)
    # 7.78万 -> 7.78 (header đã ghi nghìn NDT)
    s = re.sub(r"([\d.]+)\s*万\s*元?", r"\1", s)
    s = re.sub(r"(\d)\s*(万|千瓦|kW)", r"\1 \2", s)
    s = re.sub(r"([一-鿿])([A-Za-z0-9])", r"\1 \2", s)
    s = re.sub(r"([A-Za-z0-9])([一-鿿])", r"\1 \2", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s


def translate_column(name: str, lang="vi") -> str:
    """Dịch tên cột (đã dạng group｜item) -> vi/en."""
    if name in ("seriesid", "brand", "manufacturer", "series", "specid",
                "specname", "year", "price", "price_yuan", "status", "series_url"):
        meta = {
            "seriesid": ("Mã dòng xe", "Series ID"),
            "brand": ("Hãng xe", "Brand"),
            "manufacturer": ("Nhà sản xuất", "Manufacturer"),
            "series": ("Dòng xe", "Series"),
            "specid": ("Mã xe", "Spec ID"),
            "specname": ("Tên biến thể", "Variant"),
            "year": ("Năm", "Year"),
            "price": ("Giá (nghìn NDT)", "Price (10k CNY)"),
            "price_yuan": ("Giá (NDT)", "Price (CNY)"),
            "status": ("Trạng thái", "Status"),
            "series_url": ("Link trang xe", "Series URL"),
        }[name]
        return meta[0] if lang == "vi" else meta[1]
    if name.startswith("filter_"):
        f = name[7:]
        d = FILTER_VI if lang == "vi" else FILTER_EN
        return d.get(f, f)
    if "｜" in name:
        item = name.split("｜", 1)[1]
    else:
        item = name
    d = COL_VI if lang == "vi" else COL_EN
    if item in d:
        return d[item]
    pairs = _TERM_VI_SORTED if lang == "vi" else _TERM_EN_SORTED
    replaced = _replace_terms(item, pairs)
    cache = _hdr_cache(lang)
    cached = cache.get(item) or cache.get(replaced)
    if cached:
        return cached
    return replaced


def translate_brand(b: str, lang="vi") -> str:
    if not b:
        return b
    pairs = _TERM_VI_SORTED if lang == "vi" else _TERM_VI_SORTED
    out = _replace_terms(b, pairs)
    return out


